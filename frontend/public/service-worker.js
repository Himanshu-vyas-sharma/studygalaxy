// StudyGalaxy service worker — offline shell + cache-first for assets
const CACHE = 'studygalaxy-v1';
const SHELL = ['/', '/index.html', '/manifest.webmanifest'];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE).then((c) => c.addAll(SHELL)).then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))
    ).then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  // Never cache API calls — always network
  if (url.pathname.startsWith('/auth') || url.pathname.startsWith('/sessions') ||
      url.pathname.startsWith('/subjects') || url.pathname.startsWith('/circles') ||
      url.pathname.startsWith('/galaxy') || url.pathname.startsWith('/stats')) return;

  // Cache-first for same-origin GET
  if (url.origin === self.location.origin) {
    event.respondWith(
      caches.match(req).then((hit) => {
        if (hit) return hit;
        return fetch(req).then((res) => {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put(req, copy)).catch(() => {});
          return res;
        }).catch(() => caches.match('/index.html'));
      })
    );
  }
});
